function market(
  id: string,
  eventId: string,
  question: [string, string],
  yes: number,
  volume: number,
  endsAt: string,
  outcomeLabel?: [string, string],
) {
  return {
    id,
    eventId,
    question: localized(question[0], question[1]),
    outcomeLabel: outcomeLabel
      ? localized(outcomeLabel[0], outcomeLabel[1])
      : undefined,
    yesPriceCents: yes,
    volumeUsd: volume,
    endsAt,
    yesTokenId: `${id}-yes`,
    noTokenId: `${id}-no`,
  };
}

