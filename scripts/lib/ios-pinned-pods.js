import { readdirSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";

/**
 * iOS 构建里要固定下载地址的 CocoaPods 依赖（scripts/build-ios-release.mjs 在 pod install 之前用）。
 *
 * ## 为什么
 *
 * YttriumWrapper（@walletconnect/react-native-compat 依赖它）的上游 podspec 在 prepare_command 里用一条
 * `curl -L` 从 github.com 的 release 下载 87 MB 的 libyttrium.xcframework.zip，不校验：
 *
 *  - 打包机上每个任务的 HOME 是新的，CocoaPods 缓存随任务删掉，每次构建都重新下；
 *  - mac-01 给 git 配的 gh-proxy 只改写 git clone，管不到 curl；
 *  - 2026-09 在 mac-01 上三次里挂两次，挂了整条 pod install 重来；
 *  - 这是钱包 App，这个二进制被人换掉的话，原来的写法发现不了。
 *
 * ## 做法
 *
 * 构建时给 Podfile 加一行 `pod 'YttriumWrapper', :podspec => 'pinned-pods/YttriumWrapper.podspec'`，
 * 用我们生成的 podspec 顶替 trunk 上那份。它照抄上游同版本的 podspec，只改下载：从固定地址下（amos 上的
 * 副本，和打包机本来就要连的 api.anyfun.win 是同一台机器，不多一个外部依赖），`--fail` 加重试，下完按 sha256
 * 校验，对不上就失败。完整性靠 sha256，不靠这个地址。
 *
 * ## 为什么在构建脚本里改，不写成 config plugin
 *
 * 本地 config plugin 的文件内容进原生指纹（@expo/fingerprint 的 expoConfigPlugins），打包机在 prebuild 之前
 * 算指纹——改插件，已经装在用户手里的包就对不上之后的热更新。这里只动 prebuild 生成的 ios/。
 *
 * ## 上游升级时
 *
 * WalletConnect 换了 YttriumWrapper 的版本，pinnedPodProblems 会让测试和构建都失败。照着做：
 *  1. 改下面的 YTTRIUM_VERSION 与 sha256（取 GitHub release 页上 libyttrium.xcframework.zip 的 digest）；
 *  2. 对照新版本的上游 podspec（reown-com/yttrium 同名 tag 的 YttriumWrapper.podspec）更新 yttriumPodspec；
 *  3. 在 amos 上放新版本的副本：RN-Server `deploy/amos/install-build-dep.sh <upstream> <sha256> <路径>`，
 *     路径是 url 里 /build-deps/ 后面那一段；
 *  4. 先放副本、再合并这里的改动，否则合并之后的 iOS 构建下不到文件。
 */

/** 生成的 podspec 放在 ios/ 下的这个目录，Podfile 里按相对路径引用 */
export const PINNED_PODS_DIRECTORY = "pinned-pods";

const MARKER = "# rn-app: pinned pods (scripts/lib/ios-pinned-pods.js)";

const YTTRIUM_VERSION = "0.10.54";

/**
 * 解压、整理头文件那一段照抄上游 0.10.54；只有前面的下载与校验是我们的。
 *
 * 这段文本会原样放进 Ruby 的 `<<-SCRIPT` heredoc，那是双引号语义：反斜杠转义、`#{}` 插值都会生效。
 * 所以这里不许出现反斜杠和 `#{` / `#$` / `#@`（测试会查），也只用 ASCII——任务环境的 LANG 不归我们管。
 *
 * CocoaPods 在命令前面自己加 `set -e` 再交给 bash（1.16.2 的 --verbose 日志里看得到），curl 失败即停。
 */
function yttriumPrepareCommand({ url, sha256 }) {
  return `curl --fail --location --silent --show-error --retry 5 --retry-all-errors --connect-timeout 30 --speed-limit 1024 --speed-time 60 -o libyttrium.xcframework.zip '${url}'
if ! echo '${sha256}  libyttrium.xcframework.zip' | shasum -a 256 -c -; then
  echo 'libyttrium.xcframework.zip from ${url} is not the pinned file (sha256 ${sha256}, see scripts/lib/ios-pinned-pods.js)' >&2
  exit 1
fi
unzip -o libyttrium.xcframework.zip -d platforms/swift/
rm libyttrium.xcframework.zip

# Restructure the headers if needed
if [ -d "platforms/swift/target/ios/libyttrium.xcframework/ios-arm64/Headers/yttriumFFI" ]; then
  mv platforms/swift/target/ios/libyttrium.xcframework/ios-arm64/Headers/yttriumFFI/* platforms/swift/target/ios/libyttrium.xcframework/ios-arm64/Headers/
  rm -rf platforms/swift/target/ios/libyttrium.xcframework/ios-arm64/Headers/yttriumFFI
fi

if [ -d "platforms/swift/target/ios/libyttrium.xcframework/ios-arm64_x86_64-simulator/Headers/yttriumFFI" ]; then
  mv platforms/swift/target/ios/libyttrium.xcframework/ios-arm64_x86_64-simulator/Headers/yttriumFFI/* platforms/swift/target/ios/libyttrium.xcframework/ios-arm64_x86_64-simulator/Headers/
  rm -rf platforms/swift/target/ios/libyttrium.xcframework/ios-arm64_x86_64-simulator/Headers/yttriumFFI
fi

# Copy Swift source files directly to Headers directory for both architectures
cp -R platforms/swift/Sources/Yttrium/*.swift platforms/swift/target/ios/libyttrium.xcframework/ios-arm64/Headers/
cp -R platforms/swift/Sources/Yttrium/*.swift platforms/swift/target/ios/libyttrium.xcframework/ios-arm64_x86_64-simulator/Headers/
`;
}

/** 其余字段照抄上游 0.10.54 的 YttriumWrapper.podspec */
function yttriumPodspec(pin) {
  return `# Generated by scripts/build-ios-release.mjs from scripts/lib/ios-pinned-pods.js - do not edit.
# Upstream YttriumWrapper ${pin.version} podspec (github.com/reown-com/yttrium, tag ${pin.version}), verbatim
# except for the download in prepare_command: fixed URL, sha256 checked, fail on mismatch.
Pod::Spec.new do |s|
  s.name         = '${pin.name}'
  s.version      = '${pin.version}'
  s.summary      = '4337 implementation'
  s.description  = '4337 implementation and Chain Abstraction'
  s.homepage     = 'https://reown.com'
  s.license      = { :type => 'MIT', :file => 'LICENSE' }
  s.authors      = 'reown inc.'

  s.source       = { :git => 'https://github.com/reown-com/yttrium.git', :tag => s.version.to_s }

  s.platform     = :ios, '13.0'

  s.swift_version = '5.9'

  s.source_files = 'platforms/swift/Sources/Yttrium/**/*.{swift,h}'

  s.prepare_command = <<-SCRIPT
${yttriumPrepareCommand(pin)}SCRIPT

  s.vendored_frameworks = 'platforms/swift/target/ios/libyttrium.xcframework'
end
`;
}

export const PINNED_PODS = [
  {
    name: "YttriumWrapper",
    version: YTTRIUM_VERSION,
    // 谁要它：这个包自带的 podspec 里写着 `s.dependency "YttriumWrapper", "<版本>"`
    requiredBy: "@walletconnect/react-native-compat",
    // 只用来往 amos 上放副本（见文件头「上游升级时」），构建不从这里下
    upstream: `https://github.com/reown-com/yttrium/releases/download/${YTTRIUM_VERSION}/libyttrium.xcframework.zip`,
    url: `https://api.anyfun.win/build-deps/yttrium/${YTTRIUM_VERSION}/libyttrium.xcframework.zip`,
    // GitHub release 页上这个文件的 digest（2026-05-28 上传，86930074 字节）
    sha256: "1d8555bdd7526ec984f43e227e7fcf30a83d090a0e7d481cd5dfb2d55f0fa32b",
    podspec: yttriumPodspec,
  },
];

const TARGET_LINE = /^([ \t]*)target ['"][^'"]+['"] do[ \t]*$/m;

/**
 * 在 Podfile 的 App target 里加上钉住的 pod。
 *
 * Podfile 里显式写了外部来源（:podspec）的 pod，整个安装都用这一份，别的 pod 对它的依赖
 * （react-native-compat 的 `s.dependency "YttriumWrapper", "0.10.54"`）也解析到这里。它本来就是 App
 * target 的传递依赖，显式写一遍不改变链接进来的东西。
 */
export function pinPodfile(podfile, pins) {
  const target = TARGET_LINE.exec(podfile);
  if (!target)
    throw new Error(
      "Podfile 里找不到 `target '…' do`：prebuild 生成的 Podfile 形状变了，钉住的 pod 没处加",
    );
  const indent = `${target[1]}  `;
  const lines = [
    `${indent}${MARKER}`,
    ...pins.map(
      (pin) =>
        `${indent}pod '${pin.name}', :podspec => '${PINNED_PODS_DIRECTORY}/${pin.name}.podspec'`,
    ),
  ];
  const at = target.index + target[0].length;
  return `${podfile.slice(0, at)}\n${lines.join("\n")}${podfile.slice(at)}`;
}

/**
 * 钉住的版本还是不是依赖真正要的那个。不一致就要人来更新（文件头「上游升级时」），不能让构建
 * 装一个和依赖声明不符的版本，也不能让过期的钉子悄悄失效。
 *
 * `podspecOf(包名)` 返回那个 npm 包自带的 podspec 文本。
 */
export function pinnedPodProblems(pins, podspecOf) {
  const problems = [];
  for (const pin of pins) {
    const text = podspecOf(pin.requiredBy);
    const dependency = new RegExp(
      `\\.dependency\\s+["']${pin.name}["']\\s*(?:,\\s*["']([^"']*)["'])?`,
    ).exec(text);
    if (!dependency) {
      problems.push(
        `${pin.requiredBy} 的 podspec 已经不依赖 ${pin.name}，把它从 scripts/lib/ios-pinned-pods.js 里删掉`,
      );
      continue;
    }
    const required = dependency[1]?.replace(/^=\s*/, "");
    if (required !== pin.version)
      problems.push(
        `${pin.requiredBy} 要的 ${pin.name} 是 ${required ?? "（不限版本）"}，scripts/lib/ios-pinned-pods.js 钉的是 ${pin.version}：` +
          "按那个文件开头「上游升级时」更新版本、sha256 与 amos 上的副本",
      );
  }
  return problems;
}

/** 从项目根解析某个 npm 包，读它自带的那份 podspec */
export function packagePodspec(projectRoot, packageName) {
  const directory = dirname(
    createRequire(resolve(projectRoot, "package.json")).resolve(
      `${packageName}/package.json`,
    ),
  );
  const podspecs = readdirSync(directory).filter((entry) =>
    entry.endsWith(".podspec"),
  );
  if (podspecs.length !== 1)
    throw new Error(
      `${directory} 下应当正好有一份 .podspec，实际 ${podspecs.length} 份`,
    );
  return readFileSync(resolve(directory, podspecs[0]), "utf8");
}
